insert into system_role_permission (role_id, permission_id, tenant_id)
select r.id, p.id, r.tenant_id
from system_role r
         join system_permission p on p.tenant_id = r.tenant_id
where r.code = 'system_admin'
  and r.tenant_id = 0
on conflict (tenant_id, role_id, permission_id) do nothing;

