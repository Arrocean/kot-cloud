-- RBAC roles. super_admin is inserted and maintained manually by database operators.
create table system_role
(
    id              bigint generated by default as identity primary key,
    code            varchar(128)                          not null,
    name            varchar(128)                          not null,
    status          smallint    default 0                 not null,
    built_in        boolean     default false             not null,
    data_scope_type varchar(32) default 'ALL'::varchar    not null,
    remark          varchar(256),
    creator_id      bigint,
    create_time     timestamp   default CURRENT_TIMESTAMP not null,
    updater_id      bigint,
    update_time     timestamp   default CURRENT_TIMESTAMP not null,
    deleted         boolean     default false             not null,
    tenant_id       bigint      default 0                 not null,
    constraint uk_system_role_tenant_code unique (tenant_id, code)
);

create table system_permission
(
    id          bigint generated by default as identity primary key,
    code        varchar(128)                            not null,
    name        varchar(128)                            not null,
    resource    varchar(128)                            not null,
    action      varchar(64)                             not null,
    type        varchar(32) default 'FUNCTION'::varchar not null,
    status      smallint    default 0                   not null,
    remark      varchar(256),
    creator_id  bigint,
    create_time timestamp   default CURRENT_TIMESTAMP   not null,
    updater_id  bigint,
    update_time timestamp   default CURRENT_TIMESTAMP   not null,
    deleted     boolean     default false               not null,
    tenant_id   bigint      default 0                   not null,
    constraint uk_system_permission_tenant_code unique (tenant_id, code)
);

create table system_menu
(
    id              bigint generated by default as identity primary key,
    code            varchar(128)                        not null,
    parent_code     varchar(128),
    title           varchar(128)                        not null,
    type            varchar(32)                         not null,
    path            varchar(1024),
    icon            varchar(128),
    sort            integer   default 0                 not null,
    visible         boolean   default true              not null,
    permission_code varchar(128),
    remark          varchar(256),
    creator_id      bigint,
    create_time     timestamp default CURRENT_TIMESTAMP not null,
    updater_id      bigint,
    update_time     timestamp default CURRENT_TIMESTAMP not null,
    deleted         boolean   default false             not null,
    tenant_id       bigint    default 0                 not null,
    constraint uk_system_menu_tenant_code unique (tenant_id, code)
);

create index idx_system_menu_tenant_parent_sort
    on system_menu (tenant_id, parent_code, sort);

create table system_user_role
(
    id        bigint generated by default as identity primary key,
    user_id   bigint default 0 not null,
    role_id   bigint default 0 not null,
    tenant_id bigint default 0 not null,
    constraint uk_system_user_role unique (tenant_id, user_id, role_id)
);

create index idx_system_user_role_tenant_user
    on system_user_role (tenant_id, user_id);

create table system_role_permission
(
    id            bigint generated by default as identity primary key,
    role_id       bigint default 0 not null,
    permission_id bigint default 0 not null,
    tenant_id     bigint default 0 not null,
    constraint uk_system_role_permission unique (tenant_id, role_id, permission_id)
);

create index idx_system_role_permission_tenant_role
    on system_role_permission (tenant_id, role_id);

